#!/usr/bin/perl
# Group docfx's generated API table of contents by namespace.
#
# `docfx metadata` writes api/toc.yml as a flat list: every namespace at the same level, each
# holding its types. With 167 namespaces that is one long undifferentiated column, and related
# namespaces (RealmEngine.Core.Features.Combat, ...Features.Combat.Commands, ...) end up as
# unrelated siblings. This rewrites the file into a tree keyed on the namespace segments, with
# the first two segments as roots — RealmEngine.Core, RealmEngine.Data, Veldrath.Server, ... —
# and each remaining segment nested underneath:
#
#     RealmEngine.Core
#       Abstractions
#       Behaviors
#       Features
#         Combat
#         Crafting
#
# Run it after `docfx metadata` and before `docfx build`. Safe to run twice: the output carries a
# marker line and a second run is a no-op. `docfx metadata` regenerates the flat file on every
# build, so this is a transform, not a one-off edit.
#
# Perl, because it is the one interpreter present in both builders without installing anything:
# docs/Dockerfile's SDK image has no Python and no Node, and the deploy host cannot reach the
# Ubuntu archive to install one.
#
# Usage: perl scripts/docfx-namespace-toc.pl [api/toc.yml]

use strict;
use warnings;

my $MARKER     = '# grouped by namespace - generated by scripts/docfx-namespace-toc.pl';
my $ROOT_DEPTH = 2;
my $path       = shift(@ARGV) // 'api/toc.yml';

open(my $fh, '<', $path)
    or do { print STDERR "$path: not found - run `docfx metadata` first\n"; exit 1; };
my @lines = <$fh>;
close $fh;
chomp @lines;

if (@lines && $lines[0] eq $MARKER) {
    print "$path: already grouped, nothing to do\n";
    exit 0;
}

my $start = -1;
for my $i (0 .. $#lines) {
    if ($lines[$i] eq 'items:') { $start = $i; last; }
}
if ($start < 0) {
    print STDERR "$path: no `items:` block - leaving it untouched\n";
    exit 0;
}

# Split the flat toc into one entry per namespace, keeping its type block verbatim.
my (@entries, $current);
for my $i ($start + 1 .. $#lines) {
    my $line = $lines[$i];
    if ($line =~ /^- (?:uid|href):\s*(.*)$/) {
        $current = { uid => $1, block => [$line], types => [] };
        push @entries, $current;
    }
    elsif ($current) {
        push @{ $current->{block} }, $line;
    }
}

if (!@entries) {
    print STDERR "$path: no namespace entries found - leaving it untouched\n";
    exit 0;
}

for my $entry (@entries) {
    my ($name) = map { /^\s*name:\s*(.*)$/ ? $1 : () } @{ $entry->{block} };
    $entry->{name} = defined $name ? $name : $entry->{uid};

    my $inside_types = 0;
    for my $line (@{ $entry->{block} }[1 .. $#{ $entry->{block} }]) {
        if ($line =~ /^  items:\s*$/) { $inside_types = 1; next; }
        push @{ $entry->{types} }, $line if $inside_types;
    }
}

# Nest by segment, first ROOT_DEPTH segments as roots, preserving source order.
my @roots;
for my $entry (@entries) {
    my @segments = split /\./, $entry->{uid};
    my $root_key = @segments >= $ROOT_DEPTH
        ? join('.', @segments[ 0 .. $ROOT_DEPTH - 1 ])
        : $segments[0];

    my $node = child(\@roots, $root_key);
    if (@segments > $ROOT_DEPTH) {
        for my $segment (@segments[ $ROOT_DEPTH .. $#segments ]) {
            $node = child($node->{children}, $segment);
        }
    }

    $node->{uid}   = $entry->{uid};
    $node->{types} = $entry->{types};
}

my @out = ($MARKER, '### YamlMime:TableOfContent', 'items:');
emit($_, 0, \@out) for @roots;

open(my $out, '>', $path) or do { print STDERR "$path: cannot write: $!\n"; exit 1; };
print $out join("\n", @out) . "\n";
close $out;

print "$path: " . scalar(@entries) . " namespace(s) grouped under " . scalar(@roots) . " root(s)\n";
exit 0;

sub child {
    my ($siblings, $name) = @_;
    for my $node (@$siblings) {
        return $node if $node->{name} eq $name;
    }
    my $node = { name => $name, uid => undef, types => [], children => [] };
    push @$siblings, $node;
    return $node;
}

sub emit {
    my ($node, $depth, $out) = @_;
    my $pad = '  ' x $depth;

    if (defined $node->{uid}) {
        push @$out, "$pad- uid: $node->{uid}";
        push @$out, "$pad  name: $node->{name}";
        push @$out, "$pad  type: Namespace";
        push @$out, "$pad  items:";
    }
    else {
        # A grouping level with no namespace page of its own (for example Veldrath.Contracts).
        push @$out, "$pad- name: $node->{name}";
        push @$out, "$pad  items:";
    }

    emit($_, $depth + 1, $out) for @{ $node->{children} };

    for my $line (@{ $node->{types} }) {
        (my $body = $line) =~ s/^  //;
        push @$out, ('  ' x ($depth + 1)) . $body;
    }
}
